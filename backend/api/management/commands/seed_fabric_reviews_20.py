class Command(BaseCommand):
    help = "Добавить 20 опубликованных отзывов (оценка 5), если такого текста ещё нет в БД."

    def add_arguments(self, parser):
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Только показать, что было бы создано, без записи в БД.",
        )

    def handle(self, *args, **options):
        dry = options["dry_run"]
        now = timezone.now()
        created_n = 0
        skipped_n = 0

        if dry:
            for i, row in enumerate(FABRIC_REVIEWS, start=1):
                text = (row["text"] or "").strip()
                name = (row["name"] or "").strip()[:120]
                city = (row["city"] or "").strip()[:120]
                if Review.objects.filter(text=text).exists():
                    self.stdout.write(self.style.WARNING(f"[{i}/20] пропуск — уже есть отзыв с таким текстом"))
                    skipped_n += 1
                    continue
                self.stdout.write(self.style.NOTICE(f"[{i}/20] dry-run: создать «{name}», {city}"))
                created_n += 1
            self.stdout.write(self.style.NOTICE(f"dry-run: было бы создано {created_n}, пропусков {skipped_n}."))
            return

        with transaction.atomic():
            for i, row in enumerate(FABRIC_REVIEWS, start=1):
                text = (row["text"] or "").strip()
                name = (row["name"] or "").strip()[:120]
                city = (row["city"] or "").strip()[:120]
                if Review.objects.filter(text=text).exists():
                    self.stdout.write(self.style.WARNING(f"[{i}/20] пропуск — уже есть отзыв с таким текстом"))
                    skipped_n += 1
                    continue
                obj = Review(
                    name=name,
                    city=city,
                    reviewed_on=None,
                    text=text,
                    rating=5,
                    publication_consent=True,
                    is_moderated=True,
                    is_published=True,
                    moderated_at=now,
                    moderated_by=None,
                    submitted_from_site=False,
                    sort_order=i * 10,
                )
                obj.full_clean()
                obj.save()
                self.stdout.write(self.style.SUCCESS(f"[{i}/20] создан отзыв id={obj.pk} «{name}»"))
                created_n += 1

        self.stdout.write(self.style.SUCCESS(f"Готово: создано {created_n}, пропущено дубликатов {skipped_n}."))
